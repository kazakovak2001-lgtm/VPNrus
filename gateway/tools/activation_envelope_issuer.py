#!/usr/bin/env python3
"""B56-4A - operator-only ActivationEnvelope issuer CLI.

This is a SEPARATE tool from gateway/tools/activation_tokens.py (the
existing activation-lifecycle CLI, unchanged and unaffected by this file)
and from gateway/tools/manifest_signing.py (the EXISTING, separate manifest
signing authority). It holds a NEW, delegated activation-issuer Ed25519
private key - never the manifest signing key - and produces a signed
`ActivationEnvelope` (net.pocvpn.client.activation.ActivationEnvelope on the
Android side) that is byte-for-byte compatible with
ActivationEnvelopeCanonicalizer.canonicalBytes()/ActivationEnvelopeCodec.

## Two separate authorities, never crossed

    activation-issuer key  -> ActivationEnvelope   (THIS file)
    manifest signing key   -> EndpointManifest / SignedBootstrapBundle (manifest_signing.py, UNCHANGED)

This tool never signs a manifest, never creates an endpoint fact, never
authorizes a host/IP/port, never uses the manifest private key, and never
adds an activation key to ManifestTrustAnchors. An optional
`--bootstrap-bundle` argument only lets the operator correlate an envelope
with an ALREADY-signed SignedManifest artifact (by exact-byte SHA-256 and
its manifest version) - this tool never re-signs, re-encodes, or modifies
that artifact in any way.

## Existing activation store remains the ONE issuance authority

`issue` calls the EXISTING gateway.api.activations.issue_activation()
directly (imported, never invoked as a subprocess) - activation ID
generation, credential generation/hashing, max_devices, expiry, durable
store locking, and store schema are ALL owned by that module, unchanged.
This file adds a signed envelope wrapper around an activation
issue_activation() already created - it does not reimplement or duplicate
any part of that store.

## Private key handling (B12's `--private-key-b64` weakness NOT repeated)

manifest_signing.py's historical `--private-key-b64`/JSON-stdout
`generate-key` pattern is deliberately NOT reused here - see this module's
own `generate-key`/`issue` commands, which accept ONLY `--private-key-file
PATH` (raw 32 Ed25519 private key bytes) and never print, log, or otherwise
surface private key material.

## B56-4A does NOT perform the production ceremony

No production private key is generated by this task, and no production
activation-issuer public key is populated into Android's
FixedActivationIssuerTrustAnchors - see docs/B56_ACTIVATION_ISSUER_KEY_CEREMONY.md.
That is B56-4B, after this tooling is reviewed.

Requires the `cryptography` package (same existing dev-only dependency as
manifest_signing.py - not a gateway API runtime dependency, never imported
by gateway/api/*). Install with: pip install cryptography
"""

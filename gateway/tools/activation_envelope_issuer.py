DOMAIN_TAG = "NOVA_ACTIVATION_ENVELOPE_V1"
CANONICAL_FORMAT_VERSION = 1  # ActivationEnvelopeCanonicalizer.FORMAT_VERSION
CODEC_FORMAT_VERSION = 1  # ActivationEnvelopeCodec's outer container FORMAT_VERSION
SIGNATURE_LENGTH = 64
NONCE_LENGTH = 16  # ActivationEnvelope.NONCE_LENGTH
MAX_ENDPOINT_HINTS = 32  # ActivationEnvelope.MAX_ENDPOINT_HINTS
